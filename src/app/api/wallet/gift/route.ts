import {
  serializeGiftPromoMetadata,
  parseGiftPromoMetadata,
  buildGiftCodeCreatedRecipientEmailTemplate,
  sendStudioEmail,
} from '@/lib/email';
import {
  addClientGiftPromo,
  adjustUserBalance,
  getClientGiftPromosBySender,
  getClientGiftPromosForRecipient,
  getUserBalance,
  type ClientGiftPromoRecord,
} from '@/lib/store';

const rateLimitMap = new Map<string, { count: number; resetAt: number }>();

function isRateLimited(identifier: string, limit = 10, windowMs = 60_000): boolean {
  const now = Date.now();
  const record = rateLimitMap.get(identifier);
  if (!record || now > record.resetAt) {
    rateLimitMap.set(identifier, { count: 1, resetAt: now + windowMs });
    return false;
  }
  if (record.count >= limit) return true;
  record.count += 1;
  return false;
}

function generateGiftPromoCode(credits: number): string {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  let suffix = '';
  for (let i = 0; i < 4; i++) {
    suffix += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return `HT-GIFT-${credits}CR-${suffix}`;
}

/**
 * GET /api/wallet/gift
 * Returns all gift promo codes generated by the authenticated client (`sentGifts`)
 * as well as any gift promo codes addressed to the client's email (`receivedGifts`).
 */
export async function GET() {
  try {
    const user = await getRequestUser();
    if (!user) {
      return NextResponse.json({ error: 'Authentication required' }, { status: 401 });
    }

    const cleanEmail = user.email.trim().toLowerCase();

    if (isSupabaseConfigured() && user.id && !user.isDevFallback) {
      const admin = createAdminClient();

      // Fetch promo_codes containing client_gift metadata
      const { data: rows } = await admin
        .from('promo_codes')
        .select('id, code, credits, max_uses, used_count, is_active, description, created_at')
        .like('description', '%"kind":"client_gift"%')
        .order('created_at', { ascending: false })
        .limit(200);

      const promoIds = (rows || []).map((r) => r.id).filter(Boolean);
      const redemptionMap = new Map<string, { createdAt: string }>();

      if (promoIds.length > 0) {
        const { data: redemptions } = await admin
          .from('promo_redemptions')
          .select('promo_code_id, created_at')
          .in('promo_code_id', promoIds);

        for (const red of redemptions || []) {
          redemptionMap.set(String(red.promo_code_id), {
            createdAt: String(red.created_at),
          });
        }
      }

      const sentGifts: ClientGiftPromoRecord[] = [];
      const receivedGifts: ClientGiftPromoRecord[] = [];

      for (const row of rows || []) {
        const meta = parseGiftPromoMetadata(row.description);
        if (!meta) continue;

        const isClaimed =
          Number(row.used_count) >= Number(row.max_uses) || redemptionMap.has(String(row.id));
        const redInfo = redemptionMap.get(String(row.id));

        const record: ClientGiftPromoRecord = {
          id: String(row.id),
          code: String(row.code),
          credits: Number(row.credits),
          senderId: meta.senderId,
          senderEmail: meta.senderEmail,
          senderName: meta.senderName,
          recipientEmail: meta.recipientEmail,
          status: isClaimed ? 'claimed' : 'active',
          claimedByEmail: isClaimed ? meta.recipientEmail : null,
          claimedAt: redInfo?.createdAt || null,
          createdAt: String(row.created_at || meta.createdAt),
        };

        if (meta.senderId === user.id || meta.senderEmail === cleanEmail) {
          sentGifts.push(record);
        } else if (meta.recipientEmail === cleanEmail) {
          receivedGifts.push(record);
        }
      }

      return NextResponse.json({
        success: true,
        sentGifts,
        receivedGifts,
      });
    }

    // Offline / Dev Fallback
    return NextResponse.json({
      success: true,
      sentGifts: getClientGiftPromosBySender(cleanEmail),
      receivedGifts: getClientGiftPromosForRecipient(cleanEmail),
    });
  } catch (err) {
    console.error('Error in GET /api/wallet/gift:', err);
    return NextResponse.json({ error: 'Failed to load shared promo codes' }, { status: 500 });
  }
}

/**
 * POST /api/wallet/gift
 * Deducts `credits` from Client A's Studio Wallet and generates a 1-time promo voucher
 * locked to Client B's email (`recipientEmail`).
 */
export async function POST(req: NextRequest) {
  try {
    const user = await getRequestUser();
    if (!user) {
      return NextResponse.json({ error: 'Authentication required' }, { status: 401 });
    }

    if (user.role === 'admin') {
      return NextResponse.json(
        { error: 'Administrators cannot generate client wallet gift codes.' },
        { status: 403 }
      );
    }

    const userIdentifier = user.id || user.email.toLowerCase().trim();
    const clientIp = req.headers.get('x-forwarded-for')?.split(',')[0]?.trim() || userIdentifier;
    if (isRateLimited(`gift:user:${userIdentifier}`) || isRateLimited(`gift:ip:${clientIp}`)) {
      return NextResponse.json(
        { error: 'Too many promo generation requests. Please wait a minute and try again.' },
        { status: 429 }
      );
    }

    const body = await req.json().catch(() => ({}));
    const recipientEmail = String(body.recipientEmail || '')
      .trim()
      .toLowerCase();
    const credits = Number(body.credits);

    if (
      !recipientEmail ||
      recipientEmail.length > 254 ||
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(recipientEmail)
    ) {
      return NextResponse.json(
        { error: 'Please enter a valid recipient email address.' },
        { status: 400 }
      );
    }

    if (recipientEmail === user.email.trim().toLowerCase()) {
      return NextResponse.json(
        { error: 'Please enter a friend or family member’s email address, not your own email.' },
        { status: 400 }
      );
    }

    if (!Number.isInteger(credits) || credits < 1 || credits > 5000) {
      return NextResponse.json(
        { error: 'Please enter a valid credit amount between 1 CR and 5,000 CR.' },
        { status: 400 }
      );
    }

    const nowIso = new Date().toISOString();
    const senderName = user.name || user.email.split('@')[0] || 'Creator';

    // 1. Production / Real Supabase Path
    if (isSupabaseConfigured() && user.id && !user.isDevFallback) {
      if (!user.emailConfirmed) {
        return NextResponse.json(
          { error: 'Please verify your email address before sharing wallet credits.' },
          { status: 403 }
        );
      }

      const admin = createAdminClient();

      // Ensure wallet row exists before spending credits
      await admin
        .from('wallets')
        .upsert(
          { user_id: user.id },
          { onConflict: 'user_id', ignoreDuplicates: true }
        );

      // Ensure unique promo code
      let code = generateGiftPromoCode(credits);
      for (let attempt = 0; attempt < 5; attempt++) {
        const { data: existing } = await admin
          .from('promo_codes')
          .select('id')
          .eq('code', code)
          .maybeSingle();
        if (!existing) break;
        code = generateGiftPromoCode(credits);
      }

      const idempotencyKey = `gift:${code}:${user.id}`;
      const spendDescription = `Generated gift promo code ${code} (${credits} CR) for ${recipientEmail}`;

      // Step 1: Atomically deduct credits from sender's wallet via spend_credits RPC
      const { data: newBalanceData, error: spendErr } = await admin.rpc('spend_credits', {
        p_user: user.id,
        p_amount: credits,
        p_ref: code,
        p_key: idempotencyKey,
        p_desc: spendDescription,
      });

      if (spendErr) {
        const msg = spendErr.message || '';
        if (msg.includes('insufficient_credits') || msg.includes('wallet not found')) {
          return NextResponse.json(
            { error: `Insufficient wallet balance to share ${credits} CR.` },
            { status: 400 }
          );
        }
        return NextResponse.json(
          { error: 'Could not deduct credits from your wallet. Please try again.' },
          { status: 400 }
        );
      }

      const newWalletBalance = Number(newBalanceData ?? 0);

      // Step 2: Insert the single-use promo code into public.promo_codes
      const metadataJson = serializeGiftPromoMetadata({
        senderId: user.id,
        senderEmail: user.email,
        senderName,
        recipientEmail,
        createdAt: nowIso,
      });

      const { data: insertedPromo, error: insertErr } = await admin
        .from('promo_codes')
        .insert({
          code,
          credits,
          max_uses: 1,
          used_count: 0,
          is_active: true,
          description: metadataJson,
        })
        .select('id, code, credits, created_at')
        .single();

      if (insertErr || !insertedPromo) {
        // Compensating refund if promo insert unexpectedly failed
        await admin.rpc('ledger_post', {
          p_user: user.id,
          p_bucket: 'promo',
          p_delta: credits,
          p_type: 'refund_wallet',
          p_ref: code,
          p_key: `gift_refund:${code}:${user.id}`,
          p_desc: `Refund for failed gift promo generation ${code}`,
          p_reverses_id: null,
        });
        return NextResponse.json(
          { error: 'Failed to generate promo voucher. Your wallet balance was not charged.' },
          { status: 500 }
        );
      }

      const giftRecord: ClientGiftPromoRecord = {
        id: String(insertedPromo.id),
        code: String(insertedPromo.code),
        credits: Number(insertedPromo.credits),
        senderId: user.id,
        senderEmail: user.email.toLowerCase(),
        senderName,
        recipientEmail,
        status: 'active',
        claimedByEmail: null,
        claimedAt: null,
        createdAt: String(insertedPromo.created_at || nowIso),
      };

      // Step 3: Inner Dashboard Notifications (Sender, Recipient if registered, and Studio Owner/Admins)
      void createNotification({
        userId: user.id,
        type: 'wallet_credit',
        title: `Gift Promo Code Created · ${credits} CR`,
        message: `Promo code ${code} (${credits} CR) generated for ${recipientEmail}. Share this code with them to redeem.`,
        link: '/redeem-code?tab=share',
        actionLabel: 'Share Credits',
        entityType: 'wallet',
        entityId: code,
      });

      void (async () => {
        try {
          const { data: recipientProfile } = await admin
            .from('profiles')
            .select('id')
            .ilike('email', recipientEmail)
            .maybeSingle();

          if (recipientProfile?.id) {
            await createNotification({
              userId: recipientProfile.id,
              type: 'wallet_credit',
              title: `You Received a ${credits} CR Gift Code!`,
              message: `${senderName} (${user.email}) shared a ${credits} CR promo code (${code}) with you.`,
              link: `/redeem-code?code=${encodeURIComponent(code)}`,
              actionLabel: 'Redeem Code',
              entityType: 'wallet',
              entityId: code,
            });
          }
        } catch {
          // Ignore non-critical recipient lookup failure
        }
      })();

      void notifyAdmins({
        type: 'wallet_credit',
        title: `Client Gift Code Generated · ${credits} CR`,
        message: `${senderName} (${user.email}) generated gift promo code ${code} (${credits} CR) for ${recipientEmail}.`,
        link: `/management/ledger?customer=${encodeURIComponent(user.email)}`,
        actionLabel: 'View Ledger',
        entityType: 'wallet',
        entityId: code,
      });

      // Step 4: Dispatch Recipient Gift Email Template
      const emailDispatched = await sendStudioEmail(
        buildGiftCodeCreatedRecipientEmailTemplate({
          senderName,
          senderEmail: user.email,
          recipientEmail,
          code,
          credits,
        })
      );

      return NextResponse.json({
        success: true,
        gift: giftRecord,
        newWalletBalance,
        emailDispatched,
        message: `Generated ${credits} CR promo code (${code}) for ${recipientEmail}!`,
      });
    }

    // 2. Development / Offline Fallback Path
    const currentBal = getUserBalance(user.email);
    if (currentBal < credits) {
      return NextResponse.json(
        { error: `Insufficient wallet balance (${currentBal} CR available) to share ${credits} CR.` },
        { status: 400 }
      );
    }

    const code = generateGiftPromoCode(credits);
    const newWalletBalance = adjustUserBalance(
      user.email,
      -credits,
      `Generated gift promo code ${code} (${credits} CR) for ${recipientEmail}`
    );

    const giftRecord = addClientGiftPromo({
      id: `gift-${Date.now().toString(36)}`,
      code,
      credits,
      senderId: user.id || 'dev-client',
      senderEmail: user.email.toLowerCase(),
      senderName,
      recipientEmail,
      status: 'active',
      claimedByEmail: null,
      claimedAt: null,
      createdAt: nowIso,
    });

    const emailDispatched = await sendStudioEmail(
      buildGiftCodeCreatedRecipientEmailTemplate({
        senderName,
        senderEmail: user.email,
        recipientEmail,
        code,
        credits,
      })
    );

    return NextResponse.json({
      success: true,
      gift: giftRecord,
      newWalletBalance,
      emailDispatched,
      message: `Generated ${credits} CR promo code (${code}) for ${recipientEmail}!`,
    });
  } catch (err) {
    console.error('Error in POST /api/wallet/gift:', err);
    return NextResponse.json(
      { error: err instanceof Error ? err.message : 'Failed to generate gift promo code' },
      { status: 500 }
    );
  }
}
